-- ขั้นต่ำต่อรุ่น (BR-02 – BR-05) บังคับซ้ำที่ฐานข้อมูล
CREATE FUNCTION orders_check_model_minimum() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE v_min INTEGER;
BEGIN
  SELECT m.min_qty INTO v_min
    FROM products p JOIN product_models m ON m.code = p.model_code
   WHERE p.id = NEW.product_id;
  IF v_min IS NULL OR NEW.quantity < v_min THEN
    RAISE EXCEPTION 'quantity % is below the model minimum %', NEW.quantity, v_min
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER orders_model_minimum
  BEFORE INSERT OR UPDATE OF quantity, product_id ON orders
  FOR EACH ROW EXECUTE FUNCTION orders_check_model_minimum();

