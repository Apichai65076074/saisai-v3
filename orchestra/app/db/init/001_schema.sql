-- ---------------------------------------------------------------- เลขเอกสารถัดไป (atomic · ต่อจาก seed)
-- next_doc_no('QT') → 'QT-0001' · prefix ที่ยังไม่มีแถวจะถูกสร้างอัตโนมัติ
CREATE FUNCTION next_doc_no(p_prefix TEXT) RETURNS TEXT
LANGUAGE plpgsql AS $$
DECLARE v_no INTEGER;
BEGIN
  INSERT INTO doc_counters (prefix, n) VALUES (p_prefix, 1)
  ON CONFLICT (prefix) DO UPDATE SET n = doc_counters.n + 1
  RETURNING n INTO v_no;
  RETURN p_prefix || '-' || lpad(v_no::text, 4, '0');
END $$;

-- ---------------------------------------------------------------- "วันนี้" ของระบบ (lib/clock.ts และ worker ใช้ SQL เดียวกัน)
-- app_now() = app_settings.now หรือเวลาจริง · app_today() = วันที่เวลาไทย
CREATE FUNCTION app_now() RETURNS TIMESTAMPTZ
LANGUAGE sql STABLE AS $$
  SELECT COALESCE((SELECT value::timestamptz FROM app_settings WHERE key = 'now' AND value IS NOT NULL AND value <> ''), now())
$$;
CREATE FUNCTION app_today() RETURNS DATE
LANGUAGE sql STABLE AS $$
  SELECT (app_now() AT TIME ZONE 'Asia/Bangkok')::date
$$;
