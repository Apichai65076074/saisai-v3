-- ---------------------------------------------------------------- ออเดอร์
CREATE TABLE orders (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no        TEXT NOT NULL UNIQUE CHECK (order_no ~ '^SO-[0-9]{4,}$'),
  company_id      BIGINT NOT NULL REFERENCES companies (id),
  created_by      BIGINT NOT NULL REFERENCES users (id),
  product_id      BIGINT NOT NULL REFERENCES products (id),
  address_id      BIGINT NULL REFERENCES delivery_addresses (id),
  reorder_of      BIGINT NULL REFERENCES orders (id),
  quantity        INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 200000 AND quantity % 100 = 0),
  unit_price      NUMERIC(10,2) NOT NULL CHECK (unit_price > 0),
  logo            BOOLEAN NOT NULL DEFAULT false,
  logo_unit_price NUMERIC(10,2) NOT NULL CHECK (logo_unit_price >= 0),
  distance_km     INTEGER NOT NULL CHECK (distance_km BETWEEN 0 AND 300),
  trips           SMALLINT NOT NULL CHECK (trips >= 1),
  bottles_amount  NUMERIC(12,2) NOT NULL CHECK (bottles_amount >= 0),
  discount_rate   NUMERIC(5,4) NOT NULL CHECK (discount_rate IN (0, 0.03, 0.05, 0.07, 0.10)),
  discount_amount NUMERIC(12,2) NOT NULL CHECK (discount_amount >= 0),
  logo_amount     NUMERIC(12,2) NOT NULL CHECK (logo_amount >= 0),
  shipping_amount NUMERIC(12,2) NOT NULL CHECK (shipping_amount >= 0),
  subtotal_amount NUMERIC(12,2) NOT NULL CHECK (subtotal_amount >= 0),
  vat_amount      NUMERIC(12,2) NOT NULL CHECK (vat_amount >= 0),
  total_amount    NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
  pickup_date     DATE NOT NULL,
  payment_terms   TEXT NOT NULL CHECK (payment_terms IN ('prepay', 'credit30')),
  status          SMALLINT NOT NULL DEFAULT 1 CHECK (status BETWEEN 1 AND 6),
  shipped_at      TIMESTAMPTZ NULL,
  due_date        DATE NULL,
  note            TEXT NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK ((status = 6) = (shipped_at IS NOT NULL)),
  CHECK (due_date IS NULL OR payment_terms = 'credit30'),
  CHECK (logo = false OR quantity >= 5000),
  CHECK (total_amount = subtotal_amount + vat_amount),
  CHECK (subtotal_amount = bottles_amount - discount_amount + logo_amount + shipping_amount)
);
